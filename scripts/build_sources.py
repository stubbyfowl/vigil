"""Write SOURCES.md from data/sources.json and data/real_ranges.json, so the document never drifts from the data.

Run: .venv/bin/python scripts/build_sources.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATUS = {"verified": "Verified", "partly verified": "Summary only", "not used yet": "Not used yet"}
FIGURE = {"verified": "Verified", "partly verified": "Summary only", "team choice": "Team choice", "must_verify": "must_verify"}


def render() -> str:
    catalog = json.loads((ROOT / "data" / "sources.json").read_text())["sources"]
    ranges = json.loads((ROOT / "data" / "real_ranges.json").read_text())
    names = {s["id"]: s["title"].split(",")[0] for s in catalog}
    lines = [
        "# Sources",
        "",
        "Generated by `scripts/build_sources.py` from `data/sources.json` and `data/real_ranges.json`. Edit those files, not this one.",
        "",
        "**Read** says how much of each source the team actually read. **Verified** means the figure was read in the source or its abstract. "
        "**Summary only** means it was read in a press release or a page quoting it, so check the original before quoting it to judges. "
        "Real people's individual records are never imported, even when they are public.",
        "",
    ]
    groups: list[str] = []
    for s in catalog:
        if s["group"] not in groups:
            groups.append(s["group"])
    for group in groups:
        lines += [f"## {group}", "", "| Source | What it gives | How Vigil uses it | Read | Status |", "|---|---|---|---|---|"]
        for s in (s for s in catalog if s["group"] == group):
            lines.append(f"| [{s['title']}]({s['url'].replace(' ', '%20')}) | {s['gives']} | {s['used_for']} | {s['checked']} | {STATUS[s['status']]} |")
        lines.append("")
    lines += ["## Reference figures", "", "| Figure | Value | Status | Source | Note |", "|---|---|---|---|---|"]
    for group in ("signals", "radiation", "communication"):
        for key, fig in ranges[group].items():
            if "value" in fig:
                value = fig["value"] if not isinstance(fig["value"], list) else f"{fig['value'][0]} to {fig['value'][1]}"
            else:
                low, high = fig.get("low"), fig.get("high")
                value = f"{low} to {high} {fig['unit']}" if low is not None and high is not None else f"below {high} {fig['unit']}" if high is not None else fig["unit"]
            source = names.get(fig["source"], "") if fig["source"] else ""
            lines.append(f"| `{key}` | {value} | {FIGURE[fig['status']]} | {source} | {fig['note']} |")
    lines += [
        "",
        "## Numbers that are the team's alone",
        "",
        "These have no outside source. Do not present them as science.",
        "",
        "- Every value in `config/thresholds.yaml`, including the hard limits.",
        "- Noise, spread between people, and the size of each planted event in `backend/app/signals.py` and `backend/app/sim/generator.py`.",
        "- How proton flux becomes dose rate in the ship, the shelter factor, and the 2-hour storm warning.",
        "- The journal word list in `backend/app/engine/checkin.py`.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    (ROOT / "SOURCES.md").write_text(render())
    print("Wrote SOURCES.md")
